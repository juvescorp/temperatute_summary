/*
 * Создание консольного приложения - Статистика температуры.
Необходимо реализовать консольное приложение, которое
осуществляет считывание текстового файла csv, состоящего из
строк следующего формата:
* YEAR;MONTH;DAY;HOUR;MINUTE;TEMPERATURE
dddd;mm;dd;hh;mm;temperature
dddd - год 4 цифры
mm - месяц 2 цифры
dd - день 2 цифры
hh - часы 2 цифры
mm - минуты 2 цифры
temperature - целое число от -99 до 99
* 
* В файле хранится статистика собранная датчиком температуры за
1 календарный год. Предполагается, что датчик собирал
информацию не чаще чем 1 раз в минуту и сохранял в заданном
формате каждое значение в текстовый файл с новой строки. В
какой-то момент времени датчик мог не работать, тогда данные по
этому периоду могут отсутствовать.
* 
* Необходимо вывести статистику по каждому месяцу, с учетом
исходных данных:
• среднемесячная температура
• минимальная температура в текущем месяце
• максимальная температура в текущем месяце
Также необходимо вывести статистику за год:
• среднегодовая температура
• минимальная температура
• максимальная температура
Приложение должно обрабатывать аргументы командной строки:
минимальный набор поддерживаемых ключей:
• -h Описание функционала приложения. Список ключей, которые
обрабатывает данное приложение и их назначение.
• -f <filename.csv> входной файл csv для обработки.
• -m <номер месяца> если задан данный ключ, то выводится
только статистика за указанный месяц.
Приложение должно корректно работать на любых входных
данных, если формат csv файла не соответствует заданному, то
необходимо указать номер строки файла csv, в которой
обнаружена ошибка и не учитывать данную строку.
Приложение должно собираться при помощи утилиты make.
Все прототипы функций используемые в приложении должны быть
вынесены в отдельный файл temp_functions.h
Тексты функций - в файл temp_functions.c.
Для реализации приложения рекомендуется использовать массив
из структурного типа данных для хранения показаний датчика.
*/



#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "temp_functions.h"

// тип структуры temperature объявлен в temp_functions.h
struct temperature month[12] = {0}, year={0}; // Берём периоды: каждый месяц из 12-ти и год. Структуру обнуляем, чтобы не было случайных значений.

int days_in_month[12]={31,28,31,30,31,30,31,31,30,31,30,31};
int month_numb=0;
int month_numb_entered_correct=0;
char* filename="";
FILE *filetest,*f;
int file_exists=0;
int main(int argc, char *argv[]) {
	
// В этой программе есть:
// 1. Ввод и проверка ввода
// 2. Вычисление максимальной и минимальной температуры за период
// 3. Вычисление средней температуры за период
// 4. Вывод результата
// Программа разделена на функции, эти функции находятся в отдельном файле
// Для сборки есть Makefile, при помощи него можно собрать курсовик в один исполнемый файл, либо удалить собранные файлы, оставив исходные тексты на месте.

// проверка аргументов

// проверка количества аргументов
   input_check_arg_count(argc, argv[0]);
// проверка ввода, получение имени файла и номера месяца   
   filename=input_check(argc, argv,&month_numb);
   
   f = fopen(filename,"r"); // Открываем файл для чтения
 
    int a; // a - количество полученных из файла чисел
    int y,m,d,h,mi,t,str_number=0; // текущие год, месяц, день, час, минута, температура, номер строки в файле
    char s[100];
    // Пока мы не дойдём до конца файла, будет продолжаться цикл 
	while (!feof(f)){
	 fgets(s,100,f); // считываем строку 
	 if (feof(f)) // если конец файла - выходим из цикла
	  break;
	// else printf("%s",s); // если не конец файла - выводим строку на экран (раскомментировать для отладки) 
	
	 a = (sscanf(s, "%d; %d; %d; %d; %d; %d",&y,&m,&d,&h,&mi,&t)); // считываем из строки год, месяц, день, час, минуту, температуру
	 str_number++; // строку считали, увеличиваем счётчик строк
		// Если чисел в строке не шесть, то выводим ошибку и продолжаем цикл
	 if (!(check_count_of_values(a, s, str_number)))
	  continue;
     // Если год не между 0 и 9999, то выводим ошибку и продолжаем цикл
     if (!(check_year(y, s, str_number)))
	  continue;
     // Если месяц не между 1 и 12, то выводим ошибку и продолжаем цикл
     if (!(check_month(m, s, str_number)))
	  continue;
	  // Проверка дня:
        // 1) Если день не между 1 и 31 - ошибка
        // 2) Проверка номера дня по месяцам (в каких-то 30, в каких-то 31)
        // 3) Проверка дня в феврале (високосный - 29 и невисокосный год - 28)
	 if(!(check_day(d,m,y,days_in_month,s,str_number)))
	  continue; 
        
     // Если часы не между 0 и 23 - ошибка
     if (!(check_hour(h, s, str_number)))
	  continue;	 
     // Если минуты не между 0 и 59 - ошибка
     if (!(check_minute(mi, s, str_number)))
	  continue;
     // Если температура не между -99 и 99 - ошибка
     if (!(check_temperature(t, s, str_number)))
	  continue;
		// (Если строка считалась без ошибок)
     else {
			// Вывод, что строка в порядке (раскомментировать для отладки)
            // printf("Ok string: %d;%d;%d;%d;%d;%d\n",y,m,d,h,mi,t);
			// Если замер первый в месяце, выставляем текущее значение температуры текущим максимумом и минимумом, обозначаем, что замер в месяце существует
			get_month_min_max (m,t,month);

			// Если замер первый в году, выставляем текущее значение температуры текущим максимумом и минимумом, обозначаем, что замер в году существует
			get_year_min_max (t,&year);

			// Складываем температуры за год, чтобы получить затем среднюю
			// Не совсем правильно. Нужно складывать среднемесячные температуры, чтобы получить более точные данные
			year.sum += t;
			// Добавляем 1 замер в счётчик замеров за год
			year.count++;
			// Складываем температуры за месяц, чтобы получить затем среднюю
			month[m-1].sum += t;
			// Добавляем 1 замер в счётчик замеров за месяц
			month[m-1].count++;

            // Определяем максимум и минимум за текущий месяц и год на данный момент
                       
			// Максимум и минимум за месяц
			set_month_min_max(t,m,d,h,mi,month);

			// Максимум и минимум за год
			set_year_min_max (t,m,d,h,mi,&year);
		}
    } while ((a = (fscanf(f, "%d;%d;%d;%d;%d;%d",&y,&m,&d,&h,&mi,&t)))!=EOF); // Считываем данные, пока не наступит конец файла
    // Подсчёт средней температуры за месяц
    // Если указан конкретный месяц от 1 до 12, то нужно посчитать и вывести данные только для него
    calc_and_print_month_average(month,month_numb);

    // Подсчёт средней температуры за месяц
    // Плюс нужен показатель, что опция -m была введена и введена верно int month_entered 0 или 1; 
    // Если месяц не был введён, то считаем среднюю температуру для всех месяцев
    if ((month_numb<=0)||(month_numb>12)){
	 get_average_for_all_months(month);

    // Подсчёт средней температуры за год
     get_average_for_year(&year);
	// Вывод суммарной, средней, максимальной и минимальной температуры, количества замеров за месяц
     print_all_months_average(month);
	}
	// Вывод максимальной, минимальной и средней температуры за год
	print_year_max_min_avg (&year, month_numb);
    return 0;
}


